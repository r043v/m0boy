/* The synthesised BIOS.  The NGP's BIOS ROM (64 KiB at 0xFF0000) is not
 * shipped: like the whole NGP emulation lineage, the machine boots the
 * cartridge directly and the BIOS's entry points are hooks.  The image
 * holds the system-call table the CPU's SWI 1 vectors through (0xFFFE00),
 * an HLE opcode planted at every BIOS entry point, the default interrupt
 * stub (a bare RETI at 0xFF23DF), and the system font the SYSFONTSET call
 * expands into the character RAM.  The font is a public-domain 8x8 face
 * (Daniel Hepper's font8x8, from IBM's public-domain VGA fonts), not the
 * console's own glyphs: that is a documented deviation, a game drawing
 * through the BIOS font shows our glyphs instead of SNK's.
 *
 * The HLE hooks mirror the BIOS's documented behaviour (the register ABI
 * lives in register bank 3: A3/W3/B3/C3/D3/XHL3 hold the arguments). */
