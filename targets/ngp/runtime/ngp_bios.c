void ngp_bios_install(void) {
    unsigned i;
    memset(machine.bios, 0, NGP_BIOS_BYTES);
    for (i = 0; i < sizeof vector_table / sizeof *vector_table; i++) {
        const uint32_t v = vector_table[i];
        machine.bios[0xFE00 + i * 4 + 0] = (uint8_t)v;
        machine.bios[0xFE00 + i * 4 + 1] = (uint8_t)(v >> 8);
        machine.bios[0xFE00 + i * 4 + 2] = (uint8_t)(v >> 16);
        machine.bios[0xFE00 + i * 4 + 3] = 0;
        machine.bios[v & 0xFFFF] = HLE_OPCODE;
    }
    machine.bios[0x23DF] = 0x07;  /* the default interrupt stub: RETI */
    machine.bios[0xFFFE] = 0x68;  /* the panic loop at 0xFFFFFE: JR -2 */
    machine.bios[0xFFFF] = 0xFE;
    memcpy(machine.bios + 0x8DCF, bios_font, sizeof bios_font);
}

/* the bank-3 register ABI the BIOS's own calls use */
#define BIOS_A3  (ngp_code_b(0x30))
#define BIOS_B3  (ngp_code_b(0x35))
#define BIOS_C3  (ngp_code_b(0x34))
#define BIOS_XDE3 (ngp_code_l(0x38))
#define BIOS_XHL3 (ngp_code_l(0x3C))
static void bios_ret(void) {
    machine.cpu.pc = ngp_read32(machine.cpu.gpr[3]);
    machine.cpu.gpr[3] += 4;
}
static uint32_t bios_pop32(void) {
    const uint32_t v = ngp_read32(machine.cpu.gpr[3]);
    machine.cpu.gpr[3] += 4;
    return v;
}
static void bios_push32(uint32_t v) {
    machine.cpu.gpr[3] -= 4;
    ngp_write32(machine.cpu.gpr[3], v);
}

void ngp_bios_hle(void) {
    switch (machine.cpu.pc & 0xFFFF) {
        case VECT_SHUTDOWN & 0xFFFF: {
            /* the console powers off: the lineage's marker return address
             * and the PC stays on the hook (an idle loop) */
            (void)bios_pop32();
            bios_push32(0xBAADC0DE);
            return;
        }
        case VECT_CLOCKGEARSET & 0xFFFF:
            bios_ret();
            return;
        case VECT_RTCGET & 0xFFFF: {
            const uint32_t dst = BIOS_XHL3;
            if (dst < 0xC000)
                for (unsigned i = 0; i < 7; i++) ngp_write(dst + i, machine.rtc_latch[i]);
            bios_ret();
            return;
        }
        case VECT_INTLVSET & 0xFFFF: {
            const uint8_t level = BIOS_B3 & 7;
            const uint8_t which = BIOS_C3;
            static const struct { uint8_t reg, nibble; } map[10] = {
                { 0x0, 0 }, { 0x1, 1 }, { 0x3, 0 }, { 0x3, 1 }, { 0x4, 0 },
                { 0x4, 1 }, { 0x9, 0 }, { 0x9, 1 }, { 0xA, 0 }, { 0xA, 1 },
            };
            if (which < 10) {
                const uint8_t shift = map[which].nibble * 4;
                uint8_t *p = &machine.int_prio[map[which].reg];
                *p = (uint8_t)((*p & ~(0x7 << shift)) | (level << shift));
                ngp_write(0x70 + map[which].reg, *p);
            }
            bios_ret();
            return;
        }
        case VECT_SYSFONTSET & 0xFFFF: {
            /* expand the 1bpp font into 2bpp tiles at the character RAM:
             * each glyph becomes 8 column words, a = the set-bit colour,
             * b = the clear-bit colour (bits 4-5 and 0-1 of A3) */
            const uint8_t b = BIOS_A3 & 3;
            const uint8_t a = (BIOS_A3 >> 4) & 3;
            uint32_t dst = 0xA000;
            for (unsigned i = 0; i < 0x300; i++) { /* 96 glyphs of 8 rows */
                uint8_t c = bios_font[i >> 3][i & 7];
                for (unsigned j = 0; j < 8; j++, c <<= 1) {
                    uint16_t data = ngp_read16(dst);
                    data <<= 2;
                    if (c & 0x80) data |= a;
                    else data |= b;
                    ngp_write16(dst, data);
                    dst += 2;
                }
            }
            bios_ret();
            return;
        }
        case VECT_FLASHWRITE & 0xFFFF: {
            const uint32_t bank = BIOS_A3 ? 0x800000 : 0x200000;
            machine.flash_unlocked = 1;
            for (uint32_t i = 0; i < (uint32_t)ngp_code_w(0x34) * 64u; i++)
                ngp_write32(BIOS_XDE3 + bank + i * 4, ngp_read32(BIOS_XHL3 + i * 4));
            machine.flash_unlocked = 0;
            ngp_code_b_set(0x30, 0); /* SYS_SUCCESS */
            bios_ret();
            return;
        }
        case VECT_FLASHALLERS & 0xFFFF:
        case VECT_FLASHPROTECT & 0xFFFF:
        case VECT_ALARMSET & 0xFFFF:
        case VECT_ALARMDOWNSET & 0xFFFF:
            ngp_code_b_set(0x30, 0);
            bios_ret();
            return;
        case VECT_GEMODESET & 0xFFFF: {
            /* the mode register is write-protected: 0xAA to 0x87F0 opens
             * it, 0x55 closes it (the lineage's routine).  A3 = 0 asks the
             * K1GE-compatible (mono) mode, anything else the colour K2GE. */
            const uint8_t mode = BIOS_A3;
            ngp_write(0x87F0, 0xAA);
            ngp_write(0x87E2, mode ? 0x00 : 0x80);
            ngp_write(0x6F95, mode);
            ngp_write(0x87F0, 0x55);
            ngp_code_b_set(0x30, 0);
            bios_ret();
            return;
        }
        case VECT_FLASHERS & 0xFFFF: {
            /* the erase: for a 2 MiB cart erasing block 31 clears the save
             * window (0x3F0000, 32 KiB) */
            const uint8_t flash_block = BIOS_B3;
            if (machine.rom_size <= 0x200000 && !BIOS_A3 && flash_block == 31) {
                machine.flash_unlocked = 1;
                for (uint32_t i = 0; i < 0x8000; i += 4) ngp_write32(0x3F0000 + i, 0xFFFFFFFF);
                machine.flash_unlocked = 0;
            }
            ngp_code_b_set(0x30, 0);
            bios_ret();
            return;
        }
        case VECT_COMINIT & 0xFFFF:
            ngp_code_b_set(0x30, 0); /* COM_BUF_OK */
            bios_ret();
            return;
        case VECT_COMSENDSTART & 0xFFFF:
        case VECT_COMRECIVESTART & 0xFFFF:
            bios_ret();
            return;
        case VECT_COMCREATEDATA & 0xFFFF: {
            ngp_test_int_hdma(NGP_INT_TX0, 0x18);
            ngp_code_b_set(0x30, 0);
            bios_ret();
            return;
        }
        case VECT_COMGETDATA & 0xFFFF:
            ngp_code_b_set(0x30, 1); /* COM_BUF_EMPTY: no link cable */
            bios_ret();
            return;
        case VECT_COMONRTS & 0xFFFF:
            ngp_write(0xB2, 0);
            bios_ret();
            return;
        case VECT_COMOFFRTS & 0xFFFF:
            ngp_write(0xB2, 1);
            bios_ret();
            return;
        case VECT_COMSENDSTATUS & 0xFFFF:
            ngp_code_w_set(0x30, 0);
            bios_ret();
            return;
        case VECT_COMRECIVESTATUS & 0xFFFF:
            ngp_code_w_set(0x30, 0);
            bios_ret();
            return;
        case VECT_COMCREATEBUF & 0xFFFF: {
            ngp_test_int_hdma(NGP_INT_TX0, 0x18);
            bios_ret();
            return;
        }
        case VECT_COMGETBUF & 0xFFFF: {
            ngp_code_b_set(0x30, 1);
            ngp_test_int_hdma(NGP_INT_RX0, 0x19);
            bios_ret();
            return;
        }
        case 0x12B4: /* the BIOS's second vector: unknown, returns */
            bios_ret();
            return;
        default:
            bios_ret();
            return;
    }
}
