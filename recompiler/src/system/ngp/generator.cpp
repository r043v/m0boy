/* Neo Geo Pocket project generation, after the PC Engine generator's plan:
 * the cartridge image as C data, the interpreter runtime (the TLCS-900H
 * core, the K2GE, the T6W28 and the sound Z80), the desktop harness and the
 * PC's SDL2 window.  The recompiled TLCS-900H code follows later; until
 * then every project interprets. */
#include "m0boy/rom_external.h"
#include "m0boy/ngp_generator.h"
#include <fstream>
#include <sstream>
#include <stdexcept>

namespace m0boy::ngp {
namespace fs = std::filesystem;
namespace {

std::string read(const fs::path& path) {
    std::ifstream file(path);
    if (!file) throw std::runtime_error("Cannot read template: " + path.string());
    return { std::istreambuf_iterator<char>(file), {} };
}
void write(const fs::path& path, const std::string& data) {
    std::ofstream file(path);
    if (!file || !(file << data)) throw std::runtime_error("Cannot write generated file: " + path.string());
}
void copy_template(const fs::path& from, const fs::path& to) {
    fs::copy_file(from, to, fs::copy_options::overwrite_existing);
}
std::string replace_all(std::string s, const std::string& what, const std::string& value) {
    size_t pos = 0;
    while ((pos = s.find(what, pos)) != std::string::npos) {
        s.replace(pos, what.size(), value);
        pos += value.size();
    }
    return s;
}

/* the cartridge as C data, 16 bytes a line */
std::string rom_data(const uint8_t* data, size_t n) {
    std::ostringstream out;
    for (size_t i = 0; i < n; i++) {
        char b[8];
        snprintf(b, sizeof b, "0x%02X,", data[i]);
        out << b;
        if ((i & 15) == 15 || i + 1 == n) out << "\n";
    }
    return out.str();
}

} // namespace

bool generate(const std::filesystem::path& cartridge, const GenerateOptions& o,
              GenerateStats& stats, std::string& error) {
    try {
        std::string note;
        const std::optional<CartridgeInfo> info = inspect(cartridge, note);
        if (!info) {
            error = note;
            return false;
        }
        /* the image (the loader's padding prefix stripped, see load_flash),
         * padded to the flash's erase granularity (a whole number of
         * 256-byte pages, what the windows map) */
        const std::string raw = load_flash(cartridge, error);
        if (raw.empty()) return false;
        const std::string data = raw;
        const size_t rom_bytes = data.size();

        const auto tpl = o.meta_templates.parent_path() / "ngp";
        if (!fs::is_regular_file(tpl / "runtime" / "ngp.c")) {
            error = "The NGP templates are missing at " + tpl.string();
            return false;
        }
        const auto marker = o.output / "ngp-project.txt";
        if (fs::exists(o.output) && !fs::exists(marker) && !fs::is_empty(o.output)) {
            bool foreign = false;
            for (const auto& e : fs::directory_iterator(o.output)) foreign = foreign || e.path().filename() != "compile.log";
            if (foreign) throw std::runtime_error("Output directory is not a Neo Geo Pocket project; choose a fresh directory");
        }
        const std::string target_name = o.target == TargetId::pc ? "pc" : "desktop";
        if (fs::exists(marker)) {
            if (read(marker) != target_name + "\n")
                throw std::runtime_error("Use a separate output directory for each destination");
        }
        const bool pc_window = o.target == TargetId::pc;
        fs::create_directories(o.output / "src");
        fs::create_directories(o.output / "host");
        const fs::path src = o.output / "src";

        const bool ext_rom = g_rom_external;
        if (ext_rom) {
            write(src / "ngp_rom_id.h", rom_id_header("NGP", reinterpret_cast<const uint8_t*>(data.data()), rom_bytes, o.name));
            copy_template(o.meta_templates.parent_path() / "common/runtime/m0_rom_ext.h", src / "m0_rom_ext.h");
            write(src / "ngp_cart.c", "#include <stdint.h>\nconst uint8_t *ngp_rom_data; /* set at start-up from the ROM file */\n"
                  "const unsigned ngp_rom_size = " + std::to_string(rom_bytes) + "u;\n");
        } else
        write(src / "ngp_cart.c",
              "/* The cartridge, generated by m0recomp (the flash windows map it\n"
              " * whole; the flash saves write back through the runtime's own copy). */\n"
              "#include <stdint.h>\n\n"
              "const uint8_t ngp_rom_data[] = {\n" + rom_data(reinterpret_cast<const uint8_t*>(data.data()), rom_bytes) + "};\n"
              "const unsigned ngp_rom_size = sizeof ngp_rom_data;\n");

        /* the runtime: the machine, the TLCS-900H core, the K2GE, the T6W28,
         * the sound Z80 (the core shares the SG-1000 runtime's chip) and the
         * BIOS.  The hash header rides next to ngp.h so both mains see it. */
        for (const char* name : { "ngp.c", "ngp.h", "ngp_trace.h", "ngp_cpu.c", "ngp_gfx.c",
                                  "ngp_psg.c", "ngp_z80.c", "ngp_bios.c" })
            copy_template(tpl / "runtime" / name, src / name);
        copy_template(tpl / "host" / "ngp_hash.h", src / "ngp_hash.h");
        copy_template(o.meta_templates.parent_path() / "sg1000" / "runtime" / "z80.c", src / "z80.c");
        copy_template(o.meta_templates.parent_path() / "sg1000" / "runtime" / "z80.h", src / "z80.h");
        copy_template(o.meta_templates.parent_path() / "sg1000" / "runtime" / "z80_ops.h", src / "z80_ops.h");
        /* the input scripts' reader (the harness's --input, the window's
         * --input / --record-input) */
        copy_template(o.meta_templates.parent_path() / "consoles" / "pc" / "pc_input.h", src / "pc_input.h");
        /* the hash helpers (M0_RUN_HASH_INIT, m0_hash_bytes) the fingerprint uses */
        copy_template(o.meta_templates.parent_path() / "common" / "host" / "m0_host_util.h",
                      src / "m0_host_util.h");

        const std::string sources =
            "${SRC}/ngp.c ${SRC}/ngp_cpu.c ${SRC}/ngp_gfx.c ${SRC}/ngp_psg.c "
            "${SRC}/ngp_z80.c ${SRC}/ngp_bios.c ${SRC}/z80.c ${SRC}/ngp_cart.c";

        if (pc_window) {
            /* the SDL2 window: the shell next to src/, the cartridge embedded */
            copy_template(tpl / "platform" / "ngp_pc.c", src / "ngp_pc.c");
            for (const char* name : { "pc_frontend.c", "pc_frontend.h" })
                copy_template(o.meta_templates.parent_path() / "consoles" / "pc" / name, src / name);
            write(o.output / "CMakeLists.txt",
                  "cmake_minimum_required(VERSION 3.20)\nproject(" + o.name + "_ngp_pc C)\n"
                  "set(CMAKE_C_STANDARD 11)\n"
                  "find_package(PkgConfig REQUIRED)\n"
                  "pkg_check_modules(SDL2 REQUIRED IMPORTED_TARGET sdl2)\n"
                  "add_executable(" + o.name + "_pc src/ngp_pc.c src/pc_frontend.c "
                  "${CMAKE_CURRENT_SOURCE_DIR}/src/ngp.c ${CMAKE_CURRENT_SOURCE_DIR}/src/ngp_cpu.c "
                  "${CMAKE_CURRENT_SOURCE_DIR}/src/ngp_gfx.c ${CMAKE_CURRENT_SOURCE_DIR}/src/ngp_psg.c "
                  "${CMAKE_CURRENT_SOURCE_DIR}/src/ngp_z80.c ${CMAKE_CURRENT_SOURCE_DIR}/src/ngp_bios.c "
                  "${CMAKE_CURRENT_SOURCE_DIR}/src/z80.c ${CMAKE_CURRENT_SOURCE_DIR}/src/ngp_cart.c)\n"
                  "target_include_directories(" + o.name + "_pc PRIVATE ${CMAKE_CURRENT_SOURCE_DIR}/src)\n"
                  "target_compile_definitions(" + o.name + "_pc PRIVATE NGP_EMBEDDED" + (ext_rom ? " M0_ROM_EXTERNAL=1" : "") + ")\n"
                  "target_compile_options(" + o.name + "_pc PRIVATE -O2 -w -ffunction-sections -fdata-sections)\n"
                  "target_link_options(" + o.name + "_pc PRIVATE -Wl,--gc-sections -s)\n"
                  "target_link_libraries(" + o.name + "_pc PRIVATE PkgConfig::SDL2 m)\n");
            write(marker, target_name + "\n");
            write(o.output / "README.md",
                  "# Neo Geo Pocket project: " + o.name + "\n\n"
                  "The cartridge interpreted on the TLCS-900H/K2GE runtime; SDL2 supplies\n"
                  "the window, the keyboard and the sound.\n\n"
                  "Build: cmake -G Ninja -S . -B build && ninja -C build\n"
                  "Run: build/" + o.name + "_pc (arrows, X = A, Z = B, Enter = Option, Esc quits; "
                  "gamepad B/A = A/B, Start = Option). "
                  "--frames N and --ppm shot.ppm provide a headless run. "
                  "--record-input session.input records what the game receives "
                  "(--input script.txt plays a script); the host harness replays it: "
                  "--input session.input.\n");
            stats.regions = 0;
            stats.entries = 0;
            return true;
        }

        /* the desktop harness: the same ngp_host.c the checkout builds, with
         * the cartridge embedded and the include paths flat */
        {
            std::string harness = read(tpl / "host" / "ngp_host.c");
            harness = replace_all(harness, "#include \"../runtime/ngp.h\"", "#include \"ngp.h\"");
            write(o.output / "host" / "ngp_host.c", harness);
            write(o.output / "host" / "CMakeLists.txt",
                  "cmake_minimum_required(VERSION 3.20)\nproject(" + o.name + "_ngp_host C)\n"
                  "set(CMAKE_C_STANDARD 11)\n"
                  "if(NOT CMAKE_BUILD_TYPE)\n    set(CMAKE_BUILD_TYPE Release)\nendif()\n"
                  "set(SRC ${CMAKE_CURRENT_SOURCE_DIR}/../src)\n"
                  "add_executable(" + o.name + "_host ngp_host.c " + sources + ")\n"
                  "target_include_directories(" + o.name + "_host PRIVATE ${SRC})\n"
                  "target_compile_definitions(" + o.name + "_host PRIVATE " + (ext_rom ? "M0_ROM_EXTERNAL" : "NGP_EMBEDDED") + ")\n"
                  "target_compile_options(" + o.name + "_host PRIVATE -w)\n"
                  "target_link_libraries(" + o.name + "_host PRIVATE m)\n");
            write(marker, target_name + "\n");
            write(o.output / "README.md",
                  "# Neo Geo Pocket project: " + o.name + "\n\n"
                  "The cartridge interpreted on the TLCS-900H/K2GE runtime.\n\n"
                  "Host: cmake -G Ninja -S host -B host/build && ninja -C host/build\n"
                  "Run: host/build/" + o.name + "_host --frames 300 [--ppm shot.ppm] [--wav out.wav] "
                  "[--input script.txt] [--save-state f] [--load-state f] [--gfx-dump]\n");
            return true;
        }
    } catch (const std::exception& e) {
        error = e.what();
        return false;
    }
}

} // namespace m0boy::ngp
